const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT_DIR, 'dist-cf');
const MAX_FILE_SIZE = 25 * 1024 * 1024; // 25 MiB Cloudflare Pages limit

const COPY_TARGETS = [
    'index.html',
    'admin.html',
    'favicon.ico',
    'favicon.svg',
    'coi-serviceworker.min.js',
    'sw.js',
    '_headers',
    '_redirects',
    'assets',
    'scripts',
    'styles',
    'userscript',
    'functions'
];

function rmDirRecursive(dir) {
    if (fs.existsSync(dir)) {
        fs.rmSync(dir, { recursive: true, force: true });
    }
}

function copyRecursive(src, dest) {
    const stat = fs.statSync(src);
    if (stat.isDirectory()) {
        if (!fs.existsSync(dest)) {
            fs.mkdirSync(dest, { recursive: true });
        }
        const entries = fs.readdirSync(src);
        for (const entry of entries) {
            copyRecursive(path.join(src, entry), path.join(dest, entry));
        }
    } else {
        if (stat.size > MAX_FILE_SIZE) {
            const relPath = path.relative(ROOT_DIR, src);
            const sizeMb = (stat.size / (1024 * 1024)).toFixed(2);
            console.log(`\x1b[33m[CF Build] Skipping file > 25 MiB:\x1b[0m ${relPath} (${sizeMb} MB) -> Will load from CDN/GitHub`);
            return;
        }
        const destDir = path.dirname(dest);
        if (!fs.existsSync(destDir)) {
            fs.mkdirSync(destDir, { recursive: true });
        }
        fs.copyFileSync(src, dest);
    }
}

function walkJsFiles(dir, baseDir = dir) {
    let results = [];
    if (!fs.existsSync(dir)) return results;
    for (const entry of fs.readdirSync(dir)) {
        const full = path.join(dir, entry);
        const rel = path.relative(baseDir, full).replace(/\\/g, '/');
        if (rel.startsWith('.') || rel.startsWith('node_modules') || rel.startsWith('workers/') || rel.startsWith('experimental/') || rel.startsWith('create-method/')) {
            continue;
        }
        const stat = fs.statSync(full);
        if (stat.isDirectory()) {
            results = results.concat(walkJsFiles(full, baseDir));
        } else if (entry.endsWith('.js')) {
            results.push(rel);
        }
    }
    return results;
}

function syncToolsBundle() {
    const webToolsDir = path.resolve(ROOT_DIR, '..', 'web-tools');
    if (!fs.existsSync(webToolsDir)) return;

    const allFiles = walkJsFiles(webToolsDir);
    const helpers = [];
    const tools = [];

    for (const p of allFiles) {
        if (p.endsWith('-tool.js')) tools.push(p);
        else helpers.push(p);
    }

    helpers.sort((a, b) => {
        const getScore = (rel) => {
            const lower = (rel || '').toLowerCase();
            if (lower === 'method/finalize.js') return 1;
            if (lower === 'method/compress.js') return 2;
            if (lower === 'method/normalize.js') return 3;
            if (lower.startsWith('method/') && !lower.startsWith('method/item/')) return 4;
            if (lower.startsWith('method/item/')) return 5;
            return 6;
        };
        return getScore(a) - getScore(b) || a.localeCompare(b);
    });
    tools.sort();

    const ordered = [...helpers, ...tools];
    if (ordered.length === 0) return;

    const manifestPath = path.join(ROOT_DIR, 'scripts', 'tools-manifest.json');
    fs.writeFileSync(manifestPath, JSON.stringify({
        updatedAt: new Date().toISOString(),
        helpers,
        tools
    }, null, 2) + '\n', 'utf8');

    const chunks = [
        `/**`,
        ` * OpenFishTools Web-Tools Unified Bundle`,
        ` * Version: 1.1.0`,
        ` * Build: ${new Date().toISOString()}`,
        ` * `,
        ` * Auto-generated by OpenFishTools Web-Tools Bundler.`,
        ` * Contains: ${helpers.length} Method/Helper Engines + ${tools.length} Core Tools.`,
        ` */`,
        ``,
        `(function() {`,
        `  "use strict";`,
        ``
    ];

    for (const rel of ordered) {
        const content = fs.readFileSync(path.join(webToolsDir, rel), 'utf8');
        chunks.push(`/* === Start: tools/${rel} === */`);
        chunks.push(content.trim());
        chunks.push(`/* === End: tools/${rel} === */\n`);
    }

    chunks.push(`})();\n`);
    const bundlePath = path.join(ROOT_DIR, 'scripts', 'tools-bundle.js');
    fs.writeFileSync(bundlePath, chunks.join('\n'), 'utf8');
    console.log(`\x1b[32m[Bundler]\x1b[0m Synced scripts/tools-bundle.js & scripts/tools-manifest.json (${helpers.length} helpers, ${tools.length} tools)`);
}

console.log('\x1b[36m====================================================\x1b[0m');
console.log('\x1b[36m  Preparing Cloudflare Pages Staging Build (dist-cf) \x1b[0m');
console.log('\x1b[36m====================================================\x1b[0m\n');

syncToolsBundle();

rmDirRecursive(OUT_DIR);
fs.mkdirSync(OUT_DIR, { recursive: true });

for (const target of COPY_TARGETS) {
    const srcPath = path.join(ROOT_DIR, target);
    const destPath = path.join(OUT_DIR, target);
    if (fs.existsSync(srcPath)) {
        copyRecursive(srcPath, destPath);
    }
}

console.log('\n\x1b[32m[CF Build Done]\x1b[0m Staging folder ready at: dist-cf');
console.log('To deploy to Cloudflare Pages without pushing to GitHub, run:');
console.log('\x1b[35m  npx wrangler pages deploy dist-cf --project-name=editorstuff\x1b[0m\n');
